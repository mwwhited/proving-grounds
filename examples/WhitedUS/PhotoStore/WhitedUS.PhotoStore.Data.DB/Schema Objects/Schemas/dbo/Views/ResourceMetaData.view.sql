CREATE VIEW [dbo].[ResourceMetaData]
WITH SCHEMABINDING  
AS --
	WITH [ResourceMetaData] AS (
		SELECT 
			[Resources].[ResourceID]
			,[Resources].[Folder]
			,[Resources].[Name]
			,[ResourceAttributes].[Value]
			,[ResourceAttributeTypes].[Attribute]
		FROM [dbo].[Resources] WITH (NOLOCK)
		JOIN [dbo].[ResourceAttributes] WITH (NOLOCK)
			ON [Resources].[ResourceID] = [ResourceAttributes].[ResourceID]
		JOIN [dbo].[ResourceAttributeTypes] WITH (NOLOCK)
			ON [ResourceAttributes].[ResourceAttributeTypeID] = [ResourceAttributeTypes].[ResourceAttributeTypeID]
	), [PivotedMetaData] As (
		SELECT
			[ResourceID]
			,[Folder]
			,[Name]
			,[ImageEXIF_ApertureValue]
			,[ImageEXIF_ColorSpace]
			,[ImageEXIF_CompressedBitsPerPixel]
			,[ImageEXIF_Contrast]
			,[ImageEXIF_CustomRendered]
			,[ImageEXIF_DateTimeDigitized]
			,[ImageEXIF_DateTimeOriginal]
			,[ImageEXIF_DateTimeValue]
			,[ImageEXIF_DigitalZoomRatio]
			,[ImageEXIF_ExifVersion]
			,[ImageEXIF_ExposureBiasValue]
			,[ImageEXIF_ExposureMode]
			,[ImageEXIF_ExposureProgram]
			,[ImageEXIF_ExposureTime]
			,[ImageEXIF_FileSource]
			,[ImageEXIF_Flash]
			,[ImageEXIF_FlashpixVersion]
			,[ImageEXIF_FNumber]
			,[ImageEXIF_FocalLength]
			,[ImageEXIF_FocalLengthIn35mmFilm]
			,[ImageEXIF_FocalPlaneResolutionUnit]
			,[ImageEXIF_FocalPlaneXResolution]
			,[ImageEXIF_FocalPlaneYResolution]
			,[ImageEXIF_GainControl]
			,[ImageEXIF_ImageDescription]
			,[ImageEXIF_ImageUniqueId]
			,[ImageEXIF_ISOSpeedRatings]
			,[ImageEXIF_JPEGInterchangeFormat]
			,[ImageEXIF_JPEGInterchangeFormatLength]
			,[ImageEXIF_LightSource]
			,[ImageEXIF_Make]
			,[ImageEXIF_MaxApertureValue]
			,[ImageEXIF_MeteringMode]
			,[ImageEXIF_Model]
			,[ImageEXIF_Orientation]
			,[ImageEXIF_OtherProperties]
			,[ImageEXIF_PixelXDimension]
			,[ImageEXIF_PixelYDimension]
			,[ImageEXIF_ResolutionUnit]
			,[ImageEXIF_Saturation]
			,[ImageEXIF_SceneCaptureType]
			,[ImageEXIF_SceneType]
			,[ImageEXIF_SensingMethod]
			,[ImageEXIF_Sharpness]
			,[ImageEXIF_ShutterSpeedValue]
			,[ImageEXIF_Software]
			,[ImageEXIF_SubjectDistanceRange]
			,[ImageEXIF_SubSecTime]
			,[ImageEXIF_SubSecTimeDigitized]
			,[ImageEXIF_SubSecTimeOriginal]
			,[ImageEXIF_UserComment]
			,[ImageEXIF_WhiteBalance]
			,[ImageEXIF_XResolution]
			,[ImageEXIF_YResolution]
			,[ImageEXIF_YCbCrPositioning]
			,[Image_Height]
			,[Image_Width]
		FROM [ResourceMetaData] AS [Data]
		PIVOT (
			/*[HashColllection].[dbo].[First]*/MAX([Data].[Value])
			FOR [Data].[Attribute] IN (
				[ImageEXIF_ApertureValue]
				,[ImageEXIF_ColorSpace]
				,[ImageEXIF_CompressedBitsPerPixel]
				,[ImageEXIF_Contrast]
				,[ImageEXIF_CustomRendered]
				,[ImageEXIF_DateTimeDigitized]
				,[ImageEXIF_DateTimeOriginal]
				,[ImageEXIF_DateTimeValue]
				,[ImageEXIF_DigitalZoomRatio]
				,[ImageEXIF_ExifVersion]
				,[ImageEXIF_ExposureBiasValue]
				,[ImageEXIF_ExposureMode]
				,[ImageEXIF_ExposureProgram]
				,[ImageEXIF_ExposureTime]
				,[ImageEXIF_FileSource]
				,[ImageEXIF_Flash]
				,[ImageEXIF_FlashpixVersion]
				,[ImageEXIF_FNumber]
				,[ImageEXIF_FocalLength]
				,[ImageEXIF_FocalLengthIn35mmFilm]
				,[ImageEXIF_FocalPlaneResolutionUnit]
				,[ImageEXIF_FocalPlaneXResolution]
				,[ImageEXIF_FocalPlaneYResolution]
				,[ImageEXIF_GainControl]
				,[ImageEXIF_ImageDescription]
				,[ImageEXIF_ImageUniqueId]
				,[ImageEXIF_ISOSpeedRatings]
				,[ImageEXIF_JPEGInterchangeFormat]
				,[ImageEXIF_JPEGInterchangeFormatLength]
				,[ImageEXIF_LightSource]
				,[ImageEXIF_Make]
				,[ImageEXIF_MaxApertureValue]
				,[ImageEXIF_MeteringMode]
				,[ImageEXIF_Model]
				,[ImageEXIF_Orientation]
				,[ImageEXIF_OtherProperties]
				,[ImageEXIF_PixelXDimension]
				,[ImageEXIF_PixelYDimension]
				,[ImageEXIF_ResolutionUnit]
				,[ImageEXIF_Saturation]
				,[ImageEXIF_SceneCaptureType]
				,[ImageEXIF_SceneType]
				,[ImageEXIF_SensingMethod]
				,[ImageEXIF_Sharpness]
				,[ImageEXIF_ShutterSpeedValue]
				,[ImageEXIF_Software]
				,[ImageEXIF_SubjectDistanceRange]
				,[ImageEXIF_SubSecTime]
				,[ImageEXIF_SubSecTimeDigitized]
				,[ImageEXIF_SubSecTimeOriginal]
				,[ImageEXIF_UserComment]
				,[ImageEXIF_WhiteBalance]
				,[ImageEXIF_XResolution]
				,[ImageEXIF_YResolution]
				,[ImageEXIF_YCbCrPositioning]
				,[Image_Height]
				,[Image_Width]
			)		
		) AS [Pivoted]
	)
		SELECT 
			[ResourceID]
			,[Folder]
			,[Name]
			,[ImageEXIF_ApertureValue]
			,[ImageEXIF_ColorSpace]
			,[ImageEXIF_CompressedBitsPerPixel]
			,[ImageEXIF_Contrast]
			,[ImageEXIF_CustomRendered]
			,[ImageEXIF_DateTimeDigitized]
			,[ImageEXIF_DateTimeOriginal]
			,[ImageEXIF_DateTimeValue]
			,[ImageEXIF_DigitalZoomRatio]
			,[ImageEXIF_ExifVersion]
			,[ImageEXIF_ExposureBiasValue]
			,[ImageEXIF_ExposureMode]
			,[ImageEXIF_ExposureProgram]
			,[ImageEXIF_ExposureTime]
			,[ImageEXIF_FileSource]
			,[ImageEXIF_Flash]
			,[ImageEXIF_FlashpixVersion]
			,[ImageEXIF_FNumber]
			,[ImageEXIF_FocalLength]
			,[ImageEXIF_FocalLengthIn35mmFilm]
			,[ImageEXIF_FocalPlaneResolutionUnit]
			,[ImageEXIF_FocalPlaneXResolution]
			,[ImageEXIF_FocalPlaneYResolution]
			,[ImageEXIF_GainControl]
			,[ImageEXIF_ImageDescription]
			,[ImageEXIF_ImageUniqueId]
			,[ImageEXIF_ISOSpeedRatings]
			,[ImageEXIF_JPEGInterchangeFormat]
			,[ImageEXIF_JPEGInterchangeFormatLength]
			,[ImageEXIF_LightSource]
			,CAST([ImageEXIF_Make] AS NVARCHAR(128)) AS [ImageEXIF_Make]
			,[ImageEXIF_MaxApertureValue]
			,[ImageEXIF_MeteringMode]
			,CAST([ImageEXIF_Model] AS NVARCHAR(128)) AS [ImageEXIF_Model]
			,[ImageEXIF_Orientation]
			,[ImageEXIF_OtherProperties]
			,[ImageEXIF_PixelXDimension]
			,[ImageEXIF_PixelYDimension]
			,[ImageEXIF_ResolutionUnit]
			,[ImageEXIF_Saturation]
			,[ImageEXIF_SceneCaptureType]
			,[ImageEXIF_SceneType]
			,[ImageEXIF_SensingMethod]
			,[ImageEXIF_Sharpness]
			,[ImageEXIF_ShutterSpeedValue]
			,[ImageEXIF_Software]
			,[ImageEXIF_SubjectDistanceRange]
			,[ImageEXIF_SubSecTime]
			,[ImageEXIF_SubSecTimeDigitized]
			,[ImageEXIF_SubSecTimeOriginal]
			,[ImageEXIF_UserComment]
			,[ImageEXIF_WhiteBalance]
			,[ImageEXIF_XResolution]
			,[ImageEXIF_YResolution]
			,[ImageEXIF_YCbCrPositioning]
			,[Image_Height]
			,[Image_Width]
		FROM [PivotedMetaData]